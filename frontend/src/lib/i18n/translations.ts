export type TranslationKey = keyof typeof translations.en;

function getNested(obj: Record<string, unknown>, path: string): string | undefined {
  const parts = path.split(".");
  let cur: unknown = obj;
  for (const p of parts) {
    if (cur && typeof cur === "object" && p in cur) cur = (cur as Record<string, unknown>)[p];
    else return undefined;
  }
  return typeof cur === "string" ? cur : undefined;
}

export function translate(locale: Locale, key: string): string {
  return getNested(translations[locale] as unknown as Record<string, unknown>, key)
    ?? getNested(translations.en as unknown as Record<string, unknown>, key)
    ?? key;
}
